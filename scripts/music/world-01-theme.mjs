function flag(name, fallback) {
  const prefix = "--" + name + "=";
  const match = process.argv.find((argument) => argument.startsWith(prefix));
  return match === undefined ? fallback : match.slice(prefix.length);
}

const which = flag("stem", "both");
const outDir = resolve(flag("out", "public/assets/audio/music/world-01"));
const previewDir = flag("preview", null);
const bitrate = flag("bitrate", "96k");
const stems = which === "both" ? ["calm", "intense"] : [which];

mkdirSync(outDir, { recursive: true });
const work = mkdtempSync(join(tmpdir(), "space-typing-music-"));
try {
  for (const stem of stems) {
    const started = Date.now();
    const { bus, lufs, peak, gainDb } = mixStem(stem);
    const wav = join(work, stem + ".wav");
    writeFileSync(wav, wavBytes(bus));
    const ogg = join(outDir, stem + ".ogg");
    execFileSync("ffmpeg", [
      "-hide_banner", "-loglevel", "error", "-y",
      "-i", wav,
      "-c:a", "libopus", "-b:a", bitrate, "-vbr", "on", "-application", "audio",
      "-metadata", "title=Signal in the Void (" + stem + ")",
      "-metadata", "artist=Space Typing (generated)",
      ogg,
    ]);
    if (previewDir !== null) {
      mkdirSync(previewDir, { recursive: true });
      execFileSync("ffmpeg", [
        "-hide_banner", "-loglevel", "error", "-y", "-i", wav,
        "-lavfi", "showspectrumpic=s=1600x500:legend=1:scale=log:fscale=log:stop=16000",
        join(previewDir, stem + "-spectrum.png"),
      ]);
      execFileSync("ffmpeg", [
        "-hide_banner", "-loglevel", "error", "-y", "-i", wav,
        "-lavfi", "showwavespic=s=1600x300:split_channels=0:colors=#6fd8ff",
        join(previewDir, stem + "-wave.png"),
      ]);
      writeFileSync(join(previewDir, stem + ".wav"), wavBytes(bus));
    }
    const kib = statSync(ogg).size / 1024;
    console.log(
      JSON.stringify({
        stem,
        out: ogg,
        seconds: Number(LOOP_SECONDS.toFixed(3)),
        lufs: Number(lufs.toFixed(2)),
        peakDb: Number(peak.toFixed(2)),
        gainDb: Number(gainDb.toFixed(2)),
        sections: sectionContour(bus),
        kib: Math.round(kib),
        renderSeconds: (Date.now() - started) / 1000,
      }),
    );
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
