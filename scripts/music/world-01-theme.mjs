/** Melody bars keyed by song bar. */
function melodyPlan() {
  const plan = new Map();
  THEME_A.forEach((bar, index) => plan.set(8 + index, bar));
  THEME_A_ANSWER.forEach((bar, index) => plan.set(16 + index, bar));
  THEME_B.forEach((bar, index) => plan.set(32 + index, bar));
  THEME_B_LIFT.forEach((bar, index) => plan.set(40 + index, bar));
  return plan;
}

const at = (bar, beat = 0) => bar * BAR + beat * BEAT;

// ---------------------------------------------------------------------------
// Arrangement: one function, two intensities.
// ---------------------------------------------------------------------------

function renderStem(stem) {
  const intense = stem === "intense";
  const frames = Math.round((LOOP_SECONDS + TAIL_SECONDS) * SAMPLE_RATE);
  const buses = {
    pad: new Bus(frames),
    arp: new Bus(frames),
    melody: new Bus(frames),
    bass: new Bus(frames),
    kick: new Bus(frames),
    drums: new Bus(frames),
    fx: new Bus(frames),
    air: new Bus(frames),
  };
  const kicks = [];
  const random = rng(intense ? 9001 : 4242);
  const human = (amount) => (random() - 0.5) * amount;

  // Pads: one note per run of the same chord, so they swell instead of
  // re-attacking every bar.
  for (let bar = 0; bar < BARS; ) {
    const chord = CHORDS[bar];
    const section = sectionOf(bar);
    let end = bar + 1;
    while (end < BARS && CHORDS[end] === chord && sectionOf(end) === section) end += 1;
    const notes = VOICINGS[chord].map(midi);
    const big = section === "surge" || (intense && section !== "void");
    if (big) notes.push(notes[1] + 12);
    if (section === "void") notes.push(notes[0] - 12);
    const brightness = {
      drift: intense ? 2200 : 900,
      signal: intense ? 2600 : 1300,
      tension: intense ? 2400 : 1100,
      surge: intense ? 3400 : 1900,
      void: intense ? 1100 : 700,
      return: intense ? 2300 : 1100,
    }[section];
    const level = (intense
      ? { drift: 0.95, signal: 1, tension: 0.9, surge: 1.2, void: 0.62, return: 0.85 }
      : { drift: 0.82, signal: 1, tension: 1, surge: 1.15, void: 0.66, return: 0.85 })[section];
    const rising = section === "tension" || section === "return";
    pad(buses.pad, at(bar), (end - bar) * BAR, notes, {
      gain: (intense ? 0.045 : 0.05) * level,
      swellTo: rising ? 1.6 : 1,
      cutoff: brightness * (section === "tension" || section === "return" ? 0.7 : 1),
      cutoffEnd: brightness * (section === "tension" || section === "return" ? 1.45 : 1),
      attack: section === "drift" || section === "void" ? 1.8 : 0.9,
      release: 2.2,
      seed: bar + 3,
    });
    bar = end;
  }

  // Arpeggio: six-step up-down figure over sixteenths (it shifts against the
  // bar, which keeps the loop from feeling mechanical).
  const ARP_SHAPE = [0, 1, 2, 3, 2, 1];
  let arpStep = 0;
  for (let bar = 0; bar < BARS; bar += 1) {
    const section = sectionOf(bar);
    const chord = VOICINGS[CHORDS[bar]].map(midi);
    const tones = [chord[0] + 12, chord[1] + 12, chord[2] + 12, chord[0] + 24];
    let division = 0;
    if (intense) division = section === "void" ? (bar >= 52 ? 2 : 0) : 4;
    else if (section === "signal" || section === "return") division = 2;
    else if (section === "tension" || section === "surge") division = 4;
    else if (section === "void" && bar >= 52) division = 1;
    if (division === 0) continue;
    const steps = 4 * division;
    for (let step = 0; step < steps; step += 1) {
      const beat = step / division;
      const tone = tones[ARP_SHAPE[arpStep % ARP_SHAPE.length]];
      arpStep += 1;
      const accent = step % division === 0 ? 1 : 0.72;
      const opening = section === "tension" || section === "return" ? 0.6 + 0.5 * ((bar % 8) / 7) : 1;
      pluck(buses.arp, at(bar, beat) + human(0.004), BEAT / division, tone, {
        gain: (intense ? 0.085 : 0.07) * accent,
        cutoff: (intense ? 3000 : 1900) * opening,
        floor: intense ? 420 : 300,
        decay: division >= 4 ? 0.13 : 0.22,
        panning: step % 2 === 0 ? -0.3 : 0.3,
      });
    }
  }

  // Melody: bell (calm, chill) or saw lead doubled by a quiet bell (intense).
  const plan = melodyPlan();
  let previous = null;
  for (const [bar, notes] of plan) {
    let beat = 0;
    for (const [name, beats] of notes) {
      const note = midi(name);
      const start = at(bar, beat);
      const length = beats * BEAT * 0.94;
      if (intense) {
        lead(buses.melody, start, length, note, { gain: 0.15, from: previous, cutoff: sectionOf(bar) === "surge" ? 3600 : 3000 });
        if (sectionOf(bar) === "surge") {
          lead(buses.melody, start, length, note - 12, { gain: 0.07, from: previous === null ? null : previous - 12, cutoff: 2200, panning: -0.2 });
        }
        bell(buses.melody, start, length, note + 12, { gain: 0.045, decay: 0.9, panning: 0.25 });
      } else {
        bell(buses.melody, start, length, note, { gain: sectionOf(bar) === "surge" ? 0.18 : 0.14, decay: 1.2 });
      }
      previous = note;
      beat += beats;
    }
  }
  // Tension: a ticking ostinato that climbs every two bars (suspense).
  const TICKS = ["E5", "F5", "G5", "G#5"];
  for (let bar = 24; bar < 32; bar += 1) {
    const tick = midi(TICKS[Math.floor((bar - 24) / 2)]);
    const division = bar >= 28 ? 2 : 1;
    for (let step = 0; step < 4 * division; step += 1) {
      const start = at(bar, step / division);
      const grow = 0.6 + 0.4 * ((bar - 24) / 7);
      if (intense) lead(buses.melody, start, (BEAT / division) * 0.5, tick, { gain: 0.07 * grow, cutoff: 2400 });
      else bell(buses.melody, start, (BEAT / division) * 0.8, tick, { gain: 0.135 * grow, decay: 0.35 });
    }
  }

  // Calm Drift: a few distant bell notes; Void: an eerie high call.
  if (!intense) {
    for (const [bar, name] of [[1, "E5"], [3, "C5"], [5, "A5"], [7, "B4"]]) {
      bell(buses.melody, at(bar, 1), BEAT * 3, midi(name), { gain: 0.1, decay: 2.2, ratio: 2 });
    }
  }
  for (const [bar, name] of [[49, "E6"], [51, "C6"], [53, "A5"], [55, "B5"]]) {
    bell(buses.melody, at(bar, 2), BEAT * 2, midi(name), { gain: intense ? 0.06 : 0.085, decay: 2.6, ratio: 1.5, index: 1.4 });
  }
  if (intense) {
    // Void: fragments of theme A echo through the delay.
    for (const bar of [50, 54]) {
      let beat = 0;
      for (const [name, beats] of THEME_A[0].slice(0, 3)) {
        lead(buses.melody, at(bar, beat), beats * BEAT * 0.9, midi(name), { gain: 0.1, cutoff: 1800 });
        beat += beats;
      }
    }
  }

  // Bass.
  for (let bar = 0; bar < BARS; bar += 1) {
    const section = sectionOf(bar);
    const root = midi(ROOTS[CHORDS[bar]]);
    const drive = intense && (section === "drift" || section === "signal" || section === "surge" || (section === "return" && bar >= 58));
    if (drive) {
      // Driving eighths with octave kicks up, ducked under the kick drum.
      const pattern = [0, 0, 12, 0, 0, 0, 12, 0];
      pattern.forEach((offset, step) => {
        bass(buses.bass, at(bar, step / 2), BEAT / 2 * 0.86, root + 12 + offset, {
          kind: "pluck",
          gain: 0.2,
          cutoff: section === "surge" ? 1300 : 950,
        });
      });
      continue;
    }
    if (intense && section === "tension") {
      const division = bar >= 28 ? 4 : 2;
      for (let step = 0; step < 4 * division; step += 1) {
        bass(buses.bass, at(bar, step / division), (BEAT / division) * 0.8, root + 12, {
          kind: "pluck",
          gain: 0.19,
          cutoff: 700 + 600 * ((bar - 24) / 7),
        });
      }
      continue;
    }
    if (!intense && (section === "tension" || section === "surge")) {
      // Calm: a soft pulse on the beat keeps the suspense moving.
      const division = section === "tension" && bar >= 28 ? 2 : 1;
      for (let step = 0; step < 4 * division; step += 1) {
        bass(buses.bass, at(bar, step / division), (BEAT / division) * 0.9, root + 12, { gain: 0.15 });
      }
      continue;
    }
    // Long sub notes (Drift, Void, calm Signal/Return).
    const halves = section === "signal" || section === "return" ? 2 : 1;
    const subGain = section === "void" ? 0.13 : section === "drift" && !intense ? 0.15 : 0.19;
    for (let half = 0; half < halves; half += 1) {
      bass(buses.bass, at(bar, half * (4 / halves)), BAR / halves - 0.05, root + 12, { gain: subGain, release: 0.3 });
    }
  }

  // Drums.
  const addKick = (time, gain = 0.5, options = {}) => {
    kick(buses.kick, time, { gain, ...options });
    kicks.push(time);
  };
  for (let bar = 0; bar < BARS; bar += 1) {
    const section = sectionOf(bar);
    const phraseEnd = bar % 8 === 7;
    if (intense) {
      if (section === "void") {
        // Heartbeat: lub-dub, the pulse of the breakdown.
        addKick(at(bar, 0), 0.42, { decay: 0.4, top: 110 });
        addKick(at(bar, 0.42), 0.3, { decay: 0.35, top: 100 });
        if (bar >= 52) snare(buses.drums, at(bar, 2), { gain: 0.14, clap: true });
        if (bar >= 54) for (let step = 0; step < 8; step += 1) hat(buses.drums, at(bar, step / 2 + 0.5), { gain: 0.03 });
        continue;
      }
      const pulledBack = (section === "tension" && bar < 28) || (section === "return" && bar < 58);
      if (!pulledBack) for (let beat = 0; beat < 4; beat += 1) addKick(at(bar, beat), 0.52);
      else if (section === "tension") {
        addKick(at(bar, 0), 0.48);
        addKick(at(bar, 2.5), 0.4);
      } else addKick(at(bar, 0), 0.45);
      // Backbeat, or the Tension / Return snare build.
      const building = (section === "tension" && bar >= 28) || (section === "return" && bar >= 60);
      if (building) {
        const progress = section === "tension" ? bar - 28 : bar - 60;
        const division = progress < 2 ? 2 : 4;
        for (let step = 0; step < 4 * division; step += 1) {
          const beat = step / division;
          const swellGain = 0.08 + 0.2 * ((progress * 4 + beat) / 16);
          snare(buses.drums, at(bar, beat), { gain: swellGain, seed: 11 + step });
        }
        if (progress === 3) for (let step = 0; step < 8; step += 1) snare(buses.drums, at(bar, 3 + step / 8), { gain: 0.26, seed: 90 + step });
      } else if (section === "tension") {
        snare(buses.drums, at(bar, 2), { gain: 0.22, seed: 15 });
      } else {
        snare(buses.drums, at(bar, 1), { gain: 0.3, clap: true });
        snare(buses.drums, at(bar, 3), { gain: 0.3, clap: true, seed: 12 });
        if (section === "surge") {
          snare(buses.drums, at(bar, 1), { gain: 0.16, seed: 13 });
          snare(buses.drums, at(bar, 3), { gain: 0.16, seed: 14 });
        }
      }
      // Hats: sixteenths with accents, open hats on the off-beats.
      if (section !== "return" || bar >= 58) {
        for (let step = 0; step < 16; step += 1) {
          if ((section === "drift" || pulledBack) && step % 2 === 1) continue;
          const offbeat = step % 4 === 2;
          if (offbeat && section !== "tension") {
            hat(buses.drums, at(bar, step / 4), { gain: 0.05, open: true, panning: -0.2, seed: 40 + step });
          } else {
            hat(buses.drums, at(bar, step / 4) + human(0.003), { gain: step % 2 === 0 ? 0.05 : 0.03, seed: 60 + step });
          }
        }
      }
      if (phraseEnd && (section === "signal" || section === "surge")) {
        ["D3", "A2", "F2", "D2"].forEach((name, index) => tom(buses.drums, at(bar, 3 + index * 0.25), midi(name), { gain: 0.22, panning: 0.4 - index * 0.25 }));
      }
    } else {
      if (section === "drift") {
        if (bar % 2 === 0) {
          addKick(at(bar, 0), 0.24, { decay: 0.42, top: 100, click: 0.05 });
          addKick(at(bar, 0.42), 0.16, { decay: 0.36, top: 95, click: 0.03 });
        }
        continue;
      }
      if (section === "void") {
        addKick(at(bar, 0), 0.26, { decay: 0.44, top: 100, click: 0.05 });
        addKick(at(bar, 0.42), 0.18, { decay: 0.38, top: 95, click: 0.03 });
        continue;
      }
      // Half-time groove: relaxed but moving.
      addKick(at(bar, 0), 0.34, { click: 0.12 });
      addKick(at(bar, 2.5), 0.26, { click: 0.1 });
      if (section === "surge" || (section === "tension" && bar >= 28)) addKick(at(bar, 1.75), 0.22, { click: 0.08 });
      snare(buses.drums, at(bar, 2), { gain: section === "surge" ? 0.17 : 0.13, tone: 220, decay: 0.13 });
      const hats = section === "tension" || section === "surge" ? 16 : 8;
      for (let step = 0; step < hats; step += 1) {
        const beat = (step * 4) / hats;
        const accent = hats === 8 ? (step % 2 === 1 ? 0.034 : 0.022) : step % 4 === 2 ? 0.032 : 0.017;
        hat(buses.drums, at(bar, beat) + human(0.004), { gain: accent, seed: 70 + step });
      }
      if (section === "surge" && bar % 2 === 1) hat(buses.drums, at(bar, 3.5), { gain: 0.03, open: true, seed: 5 });
    }
  }

  // FX: risers into the peak and into the loop, crashes on big downbeats.
  if (intense) {
    riser(buses.fx, at(28), BAR * 4, { gain: 0.11 });
    riser(buses.fx, at(60), BAR * 4, { gain: 0.11, seed: 32 });
    swell(buses.fx, at(31), BAR, { gain: 0.12 });
    swell(buses.fx, at(63), BAR, { gain: 0.12, seed: 42 });
    swell(buses.fx, at(47), BAR, { gain: 0.06, seed: 43 });
    for (const bar of [0, 32]) impact(buses.fx, at(bar), { gain: 0.26, sub: 0.7 });
    for (const bar of [8, 16, 24, 36, 40, 44, 56]) impact(buses.fx, at(bar), { gain: 0.14, sub: 0, seed: 54 + bar });
  } else {
    riser(buses.fx, at(30), BAR * 2, { gain: 0.045 });
    riser(buses.fx, at(62), BAR * 2, { gain: 0.035, seed: 33 });
    swell(buses.fx, at(31), BAR, { gain: 0.05 });
    swell(buses.fx, at(63), BAR, { gain: 0.04, seed: 44 });
    impact(buses.fx, at(32), { gain: 0.08, sub: 0.4 });
  }
  atmosphere(buses.air, 0, LOOP_SECONDS, { gain: intense ? 0.018 : 0.03, loopFade: 3 });

  return { buses, kicks, frames };
}

function mixStem(stem) {
  const intense = stem === "intense";
  const { buses, kicks, frames } = renderStem(stem);

  // Clean low end: only bass and kick live below ~150 Hz.
  highPass(buses.pad, 160);
  highPass(buses.arp, 260);
  highPass(buses.melody, 240);
  highPass(buses.drums, 140);
  highPass(buses.air, 180);

  // Pump: pads and bass breathe with the kick (strongly in the intense stem).
  sidechain(buses.pad, kicks, intense ? 0.5 : 0.16, intense ? 0.2 : 0.3);
  sidechain(buses.bass, kicks, intense ? 0.62 : 0.3, 0.11);
  sidechain(buses.arp, kicks, intense ? 0.25 : 0.1, 0.16);

  // Echo: dotted-eighth ping-pong on arp and melody.
  const delayIn = new Bus(frames);
  mixInto(delayIn, buses.arp, 0.34);
  mixInto(delayIn, buses.melody, intense ? 0.22 : 0.3);
  const echo = pingPong(delayIn, BEAT * 0.75, 0.4, 3000);

  // Space: one shared hall.
  const verbIn = new Bus(frames);
  mixInto(verbIn, buses.pad, 0.3);
  mixInto(verbIn, buses.arp, 0.3);
  mixInto(verbIn, buses.melody, intense ? 0.32 : 0.5);
  mixInto(verbIn, buses.drums, 0.16);
  mixInto(verbIn, buses.fx, 0.45);
  mixInto(verbIn, echo, 0.35);
  const hall = reverb(verbIn, { room: intense ? 0.82 : 0.9, damp: 0.42, width: 1 });
  highPass(hall, 220);

  if (process.argv.includes("--balance")) {
    // K-weighted loudness of each part at its mix level: the balance at a glance.
    const parts = { ...buses, echo, hall };
    console.log(
      stem + " balance (LUFS): " +
        Object.entries(parts)
          .map(([name, bus]) => name + " " + (integratedLoudness(bus) + 20 * Math.log10(MIX[stem][name])).toFixed(1))
          .join(" | "),
    );
  }

  // Diagnostics: --solo=melody,bass or --mute=pad (spectrum checks).
  const solo = flag("solo", null)?.split(",") ?? null;
  const muted = flag("mute", "").split(",");
  const levels = Object.fromEntries(
    Object.entries(MIX[stem]).map(([name, level]) => [
      name,
      (solo !== null && !solo.includes(name)) || muted.includes(name) ? 0 : level,
    ]),
  );
  const mix = new Bus(frames);
  for (const name of ["pad", "arp", "melody", "bass", "kick", "drums", "fx", "air"]) {
    mixInto(mix, buses[name], levels[name]);
  }
  mixInto(mix, echo, levels.echo);
  mixInto(mix, hall, levels.hall);

  // Seamless loop: the tail after bar 64 wraps onto the start.
  const loop = foldLoop(mix, Math.round(LOOP_SECONDS * SAMPLE_RATE));
  // The glue compressor eats part of any gain, so converge in a few passes.
  let gainDb = TARGET_LUFS[stem] - integratedLoudness(loop);
  let mastered = master(copyBus(loop), { gainDb, ceilingDb: -1.2 });
  let lufs = integratedLoudness(mastered);
  for (let pass = 0; pass < 4 && Math.abs(lufs - TARGET_LUFS[stem]) > 0.25; pass += 1) {
    gainDb += TARGET_LUFS[stem] - lufs;
    mastered = master(copyBus(loop), { gainDb, ceilingDb: -1.2 });
    lufs = integratedLoudness(mastered);
  }
  return { bus: mastered, lufs, peak: peakDb(mastered), gainDb };
}

function copyBus(bus) {
  const copy = new Bus(bus.frames);
  copy.l.set(bus.l);
  copy.r.set(bus.r);
  return copy;
}

/** Loudness per section (LUFS): the song's rise and fall, for the report. */
function sectionContour(bus) {
  return SECTIONS.map((section) => {
    const from = Math.round(at(section.from) * SAMPLE_RATE);
    const to = Math.round(at(section.to) * SAMPLE_RATE);
    const part = new Bus(to - from);
    part.l.set(bus.l.subarray(from, to));
    part.r.set(bus.r.subarray(from, to));
    return section.name + " " + integratedLoudness(part).toFixed(1);
  }).join(" | ");
}

