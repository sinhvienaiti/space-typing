/**
 * World 01 theme "Signal in the Void": renders two stems of one song, a calm
 * stem (WORLD_NORMAL) and an intense stem (WORLD_INTENSE). Same key, tempo,
 * chords, melody and length, so the game can crossfade between them at the
 * same position and the music rises and falls with the stage pacing.
 *
 *   pnpm music:world-01            # renders both stems into public/
 *   node scripts/music/world-01-theme.mjs --stem=calm --preview=.visual/music
 *
 * A minor, 112 BPM, 64 bars (≈ 2:17 per loop), seamless loop. Sections:
 *   Drift (1–8) → Signal (9–24, theme A) → Tension (25–32, build) →
 *   Surge (33–48, theme B, peak) → Void (49–56, heartbeat breakdown) →
 *   Return (57–64, rebuild into the loop).
 *
 * Original music generated by this script (no samples, no third-party audio).
 * Guide: docs/MUSIC_WORLD_01.md.
 */
