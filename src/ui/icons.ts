export type IconName = keyof typeof PATHS;

export function isIconName(value: string): value is IconName {
  return Object.prototype.hasOwnProperty.call(PATHS, value);
}

export function iconSvg(name: IconName, className = ""): string {
  return (
    '<svg class="holo-ic' +
    (className === "" ? "" : " " + className) +
    '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    PATHS[name] +
    "</svg>"
  );
}

function maskUrl(name: IconName): string {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
    PATHS[name] +
    "</svg>";
  return 'url("data:image/svg+xml,' + encodeURIComponent(svg) + '")';
}

let installed = false;

/** One stylesheet with a mask per icon; safe to call more than once. */
export function installIconStyles(): void {
  if (installed || typeof document === "undefined") return;
  installed = true;
  const rules = (Object.keys(PATHS) as IconName[]).map(
    (name) => '[data-icon="' + name + '"]{--holo-icon:' + maskUrl(name) + "}",
  );
  const style = document.createElement("style");
  style.id = "holoIconStyles";
  style.textContent = rules.join("\n");
  document.head.append(style);
}
